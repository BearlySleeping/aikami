/**
 * Builds the resumable continuation for a move suspended at `pathIndex`.
 *
 * `committedCells` is the already-applied prefix (charged), `remainingPath`
 * excludes the mover's current cell so the resume never replays a committed
 * cell or charges it twice.
 */
export const buildMoveContinuation = (options: {
  continuationId: string;
  initiatingCommandId: string;
  combatantId: string;
  fullPath: readonly GridPoint[];
  committedPathIndex: number;
  spentMovement: number;
}): SerializableCommandContinuation => ({
  continuationId: options.continuationId,
  initiatingCommandId: options.initiatingCommandId,
  commandKind: 'move',
  combatantId: options.combatantId,
  committedCells: options.fullPath
    .slice(0, options.committedPathIndex + 1)
    .map((cell) => ({ x: cell.x, y: cell.y })),
  remainingPath: options.fullPath
    .slice(options.committedPathIndex + 1)
    .map((cell) => ({ x: cell.x, y: cell.y })),
  spentMovement: options.spentMovement,
  resolvedWindowIds: [],
  resolvedReactorIds: [],
  pendingWindowId: null,
});

/**
 * Whether the suspended command may resume after the reaction batch.
 *
 * An active or retreating mover may continue — a fleeing actor still on the
 * battlefield remains a participant. A mover that is downed, defeated,
 * removed or surrendered cannot continue: the remainder of the path is
 * cancelled. Contract: C-532 AC-2, AC-3.
 */
export const continuationCanResume = (options: {
  mover: CombatantState | undefined;
  participation: ParticipationState | undefined;
  phaseEnded: boolean;
}): boolean => {
  const { mover, participation } = options;
  if (options.phaseEnded || mover === undefined) {
    return false;
  }
  if (mover.defeated || mover.downed) {
    return false;
  }
  return (
    participation === undefined ||
    participation.status === 'active' ||
    participation.status === 'retreating'
  );
};

/** Reaction availability resets at the start of the reactor's own turn. */
export const resetReactionForTurn = (
  budget: CombatantState['budget'],
): CombatantState['budget'] => ({
  ...budget,
  reactionAvailable: true,
});
