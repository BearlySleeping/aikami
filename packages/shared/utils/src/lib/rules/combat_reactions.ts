/** Deterministic window id — no ambient randomness. */
export const reactionWindowId = (
  initiatingCommandId: string,
  pathIndex: number,
  version: number,
): string => `rw:${initiatingCommandId}:${pathIndex}:${version}`;

export const buildReactionWindow = (options: {
  initiatingCommandId: string;
  moverId: string;
  reactionId: string;
  trigger: OpportunityTriggerGroup;
  continuation: SerializableCommandContinuation;
  version: number;
}): ReactionWindow => ({
  windowId: reactionWindowId(
    options.initiatingCommandId,
    options.trigger.pathIndex,
    options.version,
  ),
  version: options.version,
  status: 'open',
  initiatingCommandId: options.initiatingCommandId,
  moverId: options.moverId,
  reactionId: options.reactionId,
  reactorQueue: [...options.trigger.reactorIds],
  currentReactorId: options.trigger.reactorIds[0] ?? null,
  triggerCell: { ...options.trigger.triggerCell },
  continuation: options.continuation,
});

/**
 * Advances the queue past the current reactor. Returns the updated window; a
 * drained queue leaves `currentReactorId = null` and the caller resolves the
 * window.
 */
export const advanceReactorQueue = (window: ReactionWindow): ReactionWindow => {
  const current = window.currentReactorId;
  if (current === null) {
    return window;
  }
  const remaining = window.reactorQueue.filter((reactorId) => reactorId !== current);
  return {
    ...window,
    version: window.version + 1,
    reactorQueue: remaining,
    currentReactorId: remaining[0] ?? null,
    // The consumed reactor is recorded so the suspended command never offers
    // it the same trigger twice.
    continuation: {
      ...window.continuation,
      resolvedReactorIds: [...new Set([...window.continuation.resolvedReactorIds, current])],
    },
  };
};

/**
 * Marks a window resolved and records it on the continuation. A resolved
 * window is never re-entered, which is what makes a duplicate choice a no-op.
 */
export const resolveReactionWindow = (window: ReactionWindow): ReactionWindow => ({
  ...window,
  version: window.version + 1,
  status: 'resolved',
  currentReactorId: null,
  continuation: {
    ...window.continuation,
    resolvedWindowIds: [...window.continuation.resolvedWindowIds, window.windowId],
    resolvedReactorIds: [...window.continuation.resolvedReactorIds],
    pendingWindowId: null,
  },
});

/**
 * Whether a reaction selection request still matches the live window.
 * A stale or duplicate request is rejected here — before any resource or RNG
 * is spent.
 */
export const reactionRequestIsCurrent = (options: {
  window: ReactionWindow | undefined;
  windowId: string;
  windowVersion: number;
  reactorId: string;
}): boolean => {
  const { window } = options;
  if (window === undefined || window.status !== 'open') {
    return false;
  }
  if (window.windowId !== options.windowId || window.version !== options.windowVersion) {
    return false;
  }
  return window.currentReactorId === options.reactorId;
};

